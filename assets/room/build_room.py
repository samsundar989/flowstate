# ---------------------------------------------------------------- geometry
class Part:
    """Triangle soup with flat per-face normals and per-vertex albedo."""

    def __init__(self):
        self.p, self.n, self.c = [], [], []

    def tri(self, a, b, c, col, normal=None):
        a, b, c = map(np.asarray, (a, b, c))
        nrm = np.cross(b - a, c - a) if normal is None else np.asarray(normal, float)
        ln = np.linalg.norm(nrm)
        if ln < 1e-12:
            return
        nrm = nrm / ln
        for v in (a, b, c):
            self.p.append(v.astype(float))
            self.n.append(nrm)
            self.c.append(col)

    def quad(self, a, b, c, d, col):  # CCW seen from the front
        self.tri(a, b, c, col)
        self.tri(a, c, d, col)

    def grid(self, origin, u, v, nu, nv, col):
        """Subdivided quad origin + s*u + t*v, front face = u x v. Subdivision gives
        the baked vertex lighting enough samples for smooth gradients."""
        o, u, v = map(np.asarray, (origin, u, v))
        for i in range(nu):
            for j in range(nv):
                a = o + u * (i / nu) + v * (j / nv)
                b = o + u * ((i + 1) / nu) + v * (j / nv)
                c = o + u * ((i + 1) / nu) + v * ((j + 1) / nv)
                d = o + u * (i / nu) + v * ((j + 1) / nv)
                self.quad(a, b, c, d, col)

    def box(self, x0, y0, z0, x1, y1, z1, col, skip=(), seg=1):
        P = lambda x, y, z: np.array([x, y, z], float)
        faces = {
            "+y": (P(x0, y1, z1), P(x1 - x0, 0, 0), P(0, 0, z0 - z1)),
            "-y": (P(x0, y0, z0), P(x1 - x0, 0, 0), P(0, 0, z1 - z0)),
            "+z": (P(x0, y0, z1), P(x1 - x0, 0, 0), P(0, y1 - y0, 0)),
            "-z": (P(x1, y0, z0), P(x0 - x1, 0, 0), P(0, y1 - y0, 0)),
            "+x": (P(x1, y0, z1), P(0, 0, z0 - z1), P(0, y1 - y0, 0)),
            "-x": (P(x0, y0, z0), P(0, 0, z1 - z0), P(0, y1 - y0, 0)),
        }
        for k, (o, u, v) in faces.items():
            if k not in skip:
                self.grid(o, u, v, seg, seg, col)

    def frustum(self, cx, y0, cz, r0, r1, h, col, segs=16, caps=(True, True), col_top=None):
        ang = [2 * math.pi * i / segs for i in range(segs + 1)]
        ring = lambda r, y: [np.array([cx + r * math.cos(t), y, cz + r * math.sin(t)]) for t in ang]
        lo, hi = ring(r0, y0), ring(r1, y0 + h)
        for i in range(segs):
            self.quad(lo[i + 1], lo[i], hi[i], hi[i + 1], col)
        if caps[0]:
            for i in range(segs):
                self.tri([cx, y0, cz], lo[i], lo[i + 1], col)
        if caps[1]:
            for i in range(segs):
                self.tri([cx, y0 + h, cz], hi[i + 1], hi[i], col_top or col)

    def leaf(self, base, direction, length, width, col):
        """A flat, slightly folded lanceolate leaf (two-sided via two windings)."""
        d = np.asarray(direction, float)
        d /= np.linalg.norm(d)
        side = np.cross(d, [0, 1, 0])
        if np.linalg.norm(side) < 1e-6:
            side = np.array([1.0, 0, 0])
        side /= np.linalg.norm(side)
        up = np.cross(side, d)
        b = np.asarray(base, float)
        pts = [b]
        for f, w in ((0.3, 0.8), (0.6, 1.0), (0.85, 0.55)):
            pts.append((f, w))
        tip = b + d * length - up * 0.25 * length  # droop
        rows = []
        for f, w in pts[1:]:
            c = b + d * length * f - up * 0.25 * length * f * f + up * 0.02 * w
            rows.append((c - side * width * w / 2, c, c + side * width * w / 2))
        prev = (b, b, b)
        for r in rows + [(tip, tip, tip)]:
            for (a0, a1), (b0, b1) in (((prev[0], prev[1]), (r[0], r[1])), ((prev[1], prev[2]), (r[1], r[2]))):
                for w in (1, -1):  # both windings -> visible from both sides
                    if w == 1:
                        self.tri(a0, b0, b1, col)
                        self.tri(a0, b1, a1, col)
                    else:
                        self.tri(a0, b1, b0, col)
                        self.tri(a0, a1, b1, col)
            prev = r


def build():
    rng = np.random.default_rng(57)
    objects = {}  # node name -> {material: Part}

    def part(obj, mat):
        return objects.setdefault(obj, {}).setdefault(mat, Part())

    # ---- shell: floor, ceiling, three walls (window opening in the left wall)
    part("Floor", "floor_wood").grid([X0, 0, Z1], [X1 - X0, 0, 0], [0, 0, Z0 - Z1], 16, 16, C["floor"])
    part("Ceiling", "ceiling").grid([X0, H, Z0], [X1 - X0, 0, 0], [0, 0, Z1 - Z0], 8, 8, C["ceiling"])
    part("WallBack", "wall_back").grid([X0, 0, Z0], [X1 - X0, 0, 0], [0, H, 0], 16, 11, C["wall_back"])
    part("WallRight", "wall").grid([X1, 0, Z0], [0, 0, Z1 - Z0], [0, H, 0], 16, 11, C["wall"])
    wl = part("WallLeft", "wall")
    # left wall faces +X: u along -Z, v along +Y. Four strips around the window.
    for (za, zb, ya, yb, nu, nv) in (
        (Z1, WZ1, 0, H, 7, 11),          # toward the viewer, full height
        (WZ0, Z0, 0, H, 4, 11),          # behind the window, full height
        (WZ1, WZ0, 0, WY0, 6, 4),        # below the window
        (WZ1, WZ0, WY1, H, 6, 3),        # above the window
    ):
        wl.grid([X0, ya, za], [0, 0, zb - za], [0, yb - ya, 0], nu, nv, C["wall"])
    # skirting boards (calm, dark)
    sk = part("Skirting", "window_frame")
    sk.box(X0, 0, Z0, X1, 0.08, Z0 + 0.015, C["frame"], skip=("-z", "-y"), seg=8)
    sk.box(X0, 0, Z0, X0 + 0.015, 0.08, Z1, C["frame"], skip=("-x", "-y"), seg=8)
    sk.box(X1 - 0.015, 0, Z0, X1, 0.08, Z1, C["frame"], skip=("+x", "-y"), seg=8)

    # ---- window: reveal, frame, mullions, glowing frosted pane (no outside geometry)
    T = 0.14  # wall thickness shown in the reveal
    rv = part("Window", "wall")
    rv.grid([X0 - T, WY0, WZ1], [T, 0, 0], [0, 0, WZ0 - WZ1], 2, 4, C["wall"])          # sill (faces +Y)
    rv.grid([X0, WY1, WZ1], [-T, 0, 0], [0, 0, WZ0 - WZ1], 2, 4, C["wall"])             # head (faces -Y)
    rv.grid([X0 - T, WY0, WZ1], [0, WY1 - WY0, 0], [T, 0, 0], 4, 2, C["wall"])          # jamb at WZ1 (faces -Z)
    rv.grid([X0, WY0, WZ0], [0, WY1 - WY0, 0], [-T, 0, 0], 4, 2, C["wall"])             # jamb at WZ0 (faces +Z)
    fr = part("Window", "window_frame")
    gx = X0 - T + 0.02
    f = 0.05
    fr.box(gx, WY0, WZ0, gx + 0.05, WY0 + f, WZ1, C["frame"])
    fr.box(gx, WY1 - f, WZ0, gx + 0.05, WY1, WZ1, C["frame"])
    fr.box(gx, WY0, WZ0, gx + 0.05, WY1, WZ0 + f, C["frame"])
    fr.box(gx, WY0, WZ1 - f, gx + 0.05, WY1, WZ1, C["frame"])
    zm, ym = (WZ0 + WZ1) / 2, WY0 + (WY1 - WY0) * 0.62
    fr.box(gx, WY0, zm - 0.02, gx + 0.05, WY1, zm + 0.02, C["frame"])
    fr.box(gx, ym - 0.02, WZ0, gx + 0.05, ym + 0.02, WZ1, C["frame"])
    fr.box(X0 - 0.01, WY0 - 0.03, WZ0 - 0.04, X0 + 0.04, WY0, WZ1 + 0.04, C["frame"])  # inner sill lip
    gl = part("Window", "glow")
    n = 6
    for i in range(n):  # vertical sky gradient (soft, no hard highlights)
        ya, yb = WY0 + (WY1 - WY0) * i / n, WY0 + (WY1 - WY0) * (i + 1) / n
        ca = sky(i / n)
        cb = sky((i + 1) / n)
        a, b = np.array([gx + 0.025, ya, WZ1]), np.array([gx + 0.025, ya, WZ0])
        c, d = np.array([gx + 0.025, yb, WZ0]), np.array([gx + 0.025, yb, WZ1])
        gl.tri(a, b, c, ca, normal=[1, 0, 0])
        gl.tri(a, c, d, ca, normal=[1, 0, 0])
        # per-vertex gradient: patch the top row colours
        gl.c[-4] = cb; gl.c[-2] = cb; gl.c[-1] = cb

    # ---- rug under the desk zone
